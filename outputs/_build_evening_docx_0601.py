from docx import Document
from docx.shared import Pt, RGBColor
from docx.oxml.ns import qn

FONT = "Microsoft YaHei"

def set_font(run, size=11, bold=False, color=None):
    run.font.name = FONT
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = RGBColor(*color)
    run._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)

doc = Document()
doc.styles['Normal'].font.name = FONT
doc.styles['Normal']._element.rPr.rFonts.set(qn('w:eastAsia'), FONT)

def H(text, size=14, color=(0x1F,0x4E,0x79)):
    p = doc.add_paragraph()
    set_font(p.add_run(text), size=size, bold=True, color=color)
    return p

def P(text, size=11, bold=False, color=None):
    p = doc.add_paragraph()
    set_font(p.add_run(text), size=size, bold=bold, color=color)
    return p

def B(text, size=11, color=None):
    p = doc.add_paragraph(style='List Bullet')
    set_font(p.add_run(text), size=size, color=color)
    return p

